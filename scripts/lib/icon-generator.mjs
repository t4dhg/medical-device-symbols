import {
  existsSync,
  readFileSync,
  readdirSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { randomUUID } from "node:crypto";
import { basename, dirname, join } from "node:path";
import { parseSvgSource } from "./svg-contract.mjs";

function compareCodePoints(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

export function iconNamesFromFilename(filename) {
  if (
    typeof filename !== "string" ||
    basename(filename) !== filename ||
    !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*\.svg$/.test(filename)
  ) {
    throw new Error(`invalid SVG filename ${JSON.stringify(filename)}`);
  }

  const iconName = filename.slice(0, -4);
  const componentName =
    iconName
      .split("-")
      .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
      .join("") + "Icon";
  const variableName = iconName.replaceAll("-", "");
  const constantName = iconName.toUpperCase().replaceAll("-", "_");

  if (
    !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(componentName) ||
    !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(variableName) ||
    !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(constantName)
  ) {
    throw new Error(
      `invalid generated identifier for ${JSON.stringify(filename)}`,
    );
  }

  return { iconName, componentName, variableName, constantName };
}

function assertUniqueNames(iconData) {
  for (const key of ["componentName", "variableName", "constantName"]) {
    const seen = new Map();
    for (const icon of iconData) {
      const previous = seen.get(icon[key]);
      if (previous !== undefined) {
        throw new Error(
          `generated ${key} collision between ${JSON.stringify(previous)} and ${JSON.stringify(icon.filename)}`,
        );
      }
      seen.set(icon[key], icon.filename);
    }
  }
}

function escapeTemplateLiteral(value) {
  return value
    .replaceAll("\\", "\\\\")
    .replaceAll("`", "\\`")
    .replaceAll("${", "\\${");
}

function renderIndex(iconData) {
  let output = `// AUTO-GENERATED by scripts/generate-index.mjs. DO NOT EDIT MANUALLY.
// To change an icon, edit its SVG in src/icons/ and run: npm run generate

import React from "react";

// Base icon component interface
export interface IconProps extends React.SVGProps<SVGSVGElement> {
  /** Width and height, as a pixel number or any CSS length. Defaults to 24. */
  size?: number | string;
  /**
   * Accessible label. When set, the icon renders with role="img" and this
   * value as its aria-label. Omit it for decorative icons and add aria-hidden.
   */
  title?: string;
}

// Base icon component factory
const createIcon = (
  displayName: string,
  svgContent: string,
  viewBox: string = "0 0 200 200"
) => {
  const IconComponent = React.forwardRef<SVGSVGElement, IconProps>(
    ({ size = 24, title, children, ...props }, ref) => {
      return React.createElement("svg", {
        ref,
        width: size,
        height: size,
        viewBox,
        fill: "currentColor",
        xmlns: "http://www.w3.org/2000/svg",
        ...(title ? { role: "img", "aria-label": title } : {}),
        ...props,
        dangerouslySetInnerHTML: { __html: svgContent },
      });
    }
  );

  IconComponent.displayName = displayName;
  return IconComponent;
};

`;

  for (const icon of iconData) {
    output += `// SVG content for ${icon.iconName}\n`;
    output += `const ${icon.variableName}SvgContent = \`${escapeTemplateLiteral(icon.markup)}\`;\n\n`;
  }

  output += "// Icon components\n";
  for (const icon of iconData) {
    output += `export const ${icon.componentName} = createIcon(\n`;
    output += `  "${icon.componentName}",\n`;
    output += `  ${icon.variableName}SvgContent,\n`;
    output += `  "${icon.viewBox}"\n`;
    output += ");\n\n";
  }

  output += "// Export all icons in an object for compatibility\n";
  output += "export const icons = {\n";
  for (const icon of iconData) {
    output += `  ${icon.componentName},\n`;
  }
  output += "};\n\n";

  output += "// Icon name constants\n";
  output += "export const ICON_NAMES = {\n";
  for (const icon of iconData) {
    output += `  ${icon.constantName}: "${icon.iconName}",\n`;
  }
  output += "} as const;\n\n";
  output += "// Type for icon names\n";
  output += "export type IconName = typeof ICON_NAMES[keyof typeof ICON_NAMES];\n";
  return output;
}

export function generateIndex({ iconsDirectory }) {
  if (typeof iconsDirectory !== "string" || iconsDirectory === "") {
    throw new TypeError("generateIndex requires an iconsDirectory");
  }
  const files = readdirSync(iconsDirectory)
    .filter((name) => name.endsWith(".svg"))
    .sort(compareCodePoints);
  if (files.length === 0) {
    throw new Error(`no SVG files found in ${iconsDirectory}`);
  }

  const iconData = files.map((filename) => {
    const names = iconNamesFromFilename(filename);
    const source = readFileSync(join(iconsDirectory, filename), "utf8");
    return {
      filename,
      ...names,
      ...parseSvgSource(source, { filename }),
    };
  });
  assertUniqueNames(iconData);
  return renderIndex(iconData);
}

export function writeOrCheckGeneratedIndex({
  iconsDirectory,
  outputFile,
  check,
}) {
  if (typeof outputFile !== "string" || outputFile === "") {
    throw new TypeError("writeOrCheckGeneratedIndex requires an outputFile");
  }
  const expected = generateIndex({ iconsDirectory });
  const actual = existsSync(outputFile)
    ? readFileSync(outputFile, "utf8")
    : undefined;

  if (check) {
    if (actual !== expected) {
      throw new Error(
        "generated src/index.tsx is out of date; run npm run generate",
      );
    }
    return;
  }
  if (actual === expected) {
    return;
  }

  const temporaryFile = join(
    dirname(outputFile),
    `.${basename(outputFile)}.${process.pid}.${randomUUID()}.tmp`,
  );
  try {
    writeFileSync(temporaryFile, expected, { encoding: "utf8", flag: "wx" });
    renameSync(temporaryFile, outputFile);
  } finally {
    if (existsSync(temporaryFile)) {
      unlinkSync(temporaryFile);
    }
  }
}
